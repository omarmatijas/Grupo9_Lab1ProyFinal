    private void iniciarConexion() throws SQLException {
        String url = "jdbc:mariadb://" + HOST + ":" + PORT + "/" + DB_NAME;
        con = new Conexion(
                url,
                USER,
                PASSWORD
        );
        if (con.buscarConexion() == null) {
            throw new SQLException("No se pudo conectar a " + url);
        }
    }
    
