    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String dni = txtDni.getText().trim();
        if (dni.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresá un DNI para buscar.");
            return;
        }
        try {
            Entrenador e = entrenadorData.buscarEntrenadorPorDNI(dni);
            if (e == null) {
                JOptionPane.showMessageDialog(this, "No existe un entrenador con ese DNI.");
            } else {
                mostrarEntrenador(e);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo buscar el entrenador: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void tablaEntrenadoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaEntrenadoresMouseClicked
        int fila = tablaEntrenadores.getSelectedRow();
        if (fila >= 0) {
            int id = Integer.parseInt(modeloTabla.getValueAt(fila, 0).toString());
            try {
                Entrenador e = entrenadorData.obtenerEntrenador(id);
                if (e != null) {
                    mostrarEntrenador(e);
                }
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "No se pudo cargar el entrenador: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_tablaEntrenadoresMouseClicked


