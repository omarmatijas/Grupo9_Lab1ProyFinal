    private void btnAltaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAltaActionPerformed
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccioná un entrenador de la tabla.");
            return;
        }
        try {
            entrenadorData.reactivacionLogicaEntrenador(Integer.parseInt(txtId.getText()));
            JOptionPane.showMessageDialog(this, "Entrenador dado de alta.");
            limpiar();
            cargarTabla();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo dar de alta: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnAltaActionPerformed

